use std::{
   collections::BTreeSet,
   fmt::Write as _,
   path::{
      Component,
      Path,
      PathBuf,
   },
};

use thiserror::Error;

use crate::{
   lock::{
      self,
      Lock,
   },
   project::{
      Damlc,
      Dependency,
      Location,
      Project,
   },
   registry,
   workspace::Workspace,
};

#[derive(Debug, Error)]
pub enum Error {
   #[error("two packages are named {0:?}")]
   DuplicatePackage(String),
   #[error("package {package:?} at {root} is outside the workspace root")]
   OutsideRoot { package: String, root: PathBuf },
   #[error("package {package:?} has source {directory} outside its own directory")]
   SourceOutside {
      package:   String,
      directory: PathBuf,
   },
   #[error("package {0:?} pins damlc through components, only sdk-version is supported")]
   UnsupportedDamlc(String),
   #[error("failed to pin {dependency}")]
   Pin {
      dependency: String,
      #[source]
      source:     registry::Error,
   },
}

pub fn render(
   workspace: &Workspace,
   root: &Path,
   output_dir: &Path,
   lock: &mut Lock,
) -> Result<String, Error> {
   let mut names = BTreeSet::new();
   let mut nix = String::new();

   for package in &workspace.packages {
      if !names.insert(package.name.as_str()) {
         return Err(Error::DuplicatePackage(package.name.clone()));
      }

      let path = package.root.strip_prefix(root).map_err(|_| {
         Error::OutsideRoot {
            package: package.name.clone(),
            root:    package.root.clone(),
         }
      })?;

      let source = package.source.strip_prefix(&package.root).map_err(|_| {
         Error::SourceOutside {
            package:   package.name.clone(),
            directory: package.source.clone(),
         }
      })?;

      let Damlc::Sdk(sdk_version) = &package.damlc else {
         return Err(Error::UnsupportedDamlc(package.name.clone()));
      };

      let dependencies = render_dependencies(&package.dependencies, workspace, output_dir, lock)?;
      let data_dependencies =
         render_dependencies(&package.data_dependencies, workspace, output_dir, lock)?;

      let _ = write!(
         nix,
         "    {name} = buildDamlPackage {{\n      name = {name};\n      version = {version};\n      \
          sdkVersion = {sdk_version};\n      root = {root};\n      path = {path};\n      \
          source = {source};\n      dependencies = {dependencies};\n      dataDependencies = {data_dependencies};\n    \
          }};\n",
         name = string(&package.name),
         version = string(&package.version),
         sdk_version = string(sdk_version),
         root = path_literal(&relative(output_dir, root)),
         path = string(&dotted(path)),
         source = string(&dotted(source)),
      );
   }

   let (arguments, registry) = if lock.dependencies.is_empty() {
      ("", String::new())
   } else {
      (
         ", fetchOciDar",
         format!(
            "  lock = builtins.fromJSON (builtins.readFile ./{});\n  registry =\n    uri:\n    \
             let\n      pin = lock.dependencies.${{uri}};\n    in\n    fetchOciDar {{\n      \
             inherit uri;\n      manifestDigest = pin.manifest;\n      darDigest = pin.dar;\n      \
             insecure = pin.insecure or false;\n    }};\n",
            lock::FILE_NAME,
         ),
      )
   };

   Ok(format!(
      "# Generated by daml2nix. Do not edit.\n{{ buildDamlPackage{arguments} }}:\nlet\n{registry}  \
       packages = {{\n{nix}  }};\nin\npackages\n",
   ))
}

fn render_dependencies(
   dependencies: &[Dependency],
   workspace: &Workspace,
   output_dir: &Path,
   lock: &mut Lock,
) -> Result<String, Error> {
   let mut items = Vec::with_capacity(dependencies.len());

   for dependency in dependencies {
      items.push(match &dependency.location {
         Location::Builtin(name) => string(name),
         Location::Dar(dar) => {
            match workspace.producer(dar) {
               Some(Project { name, .. }) => format!("packages.{}.dar", string(name)),
               None => path_literal(&relative(output_dir, dar)),
            }
         },
         Location::Oci {
            reference,
            insecure,
         } => {
            let pinned = registry::pin(reference, *insecure, dependency.main_package_id.as_deref())
               .map_err(|source| {
                  Error::Pin {
                     dependency: reference.to_string(),
                     source,
                  }
               })?;

            let uri = reference.to_string();
            let item = format!("(registry {})", string(&uri));

            lock.dependencies.insert(uri, lock::Dependency {
               manifest: pinned.manifest_digest,
               dar:      pinned.dar_digest,
               insecure: *insecure,
               audit:    None,
            });

            item
         },
      });
   }

   if items.is_empty() {
      return Ok("[ ]".to_owned());
   }

   let mut nix = String::from("[\n");

   for item in items {
      let _ = writeln!(nix, "        {item}");
   }

   nix.push_str("      ]");
   Ok(nix)
}

fn dotted(path: &Path) -> String {
   if path.as_os_str().is_empty() {
      ".".to_owned()
   } else {
      path.to_string_lossy().into_owned()
   }
}

fn relative(from: &Path, to: &Path) -> PathBuf {
   let common = from
      .components()
      .zip(to.components())
      .take_while(|(left, right)| left == right)
      .count();

   from
      .components()
      .skip(common)
      .map(|_| Component::ParentDir.as_os_str())
      .chain(to.components().skip(common).map(Component::as_os_str))
      .collect()
}

fn path_literal(path: &Path) -> String {
   let path = path.to_string_lossy();

   if path.is_empty() {
      return "./.".to_owned();
   }

   let plain = path
      .chars()
      .all(|ch| ch.is_ascii_alphanumeric() || "._-+/".contains(ch));

   if plain {
      format!("./{path}")
   } else {
      format!("(./. + {})", string(&format!("/{path}")))
   }
}

fn string(value: &str) -> String {
   let mut nix = String::with_capacity(value.len() + 2);
   nix.push('"');

   let mut chars = value.chars().peekable();

   while let Some(ch) = chars.next() {
      match ch {
         '"' => nix.push_str("\\\""),
         '\\' => nix.push_str("\\\\"),
         '\n' => nix.push_str("\\n"),
         '$' if chars.peek() == Some(&'{') => nix.push_str("\\$"),
         other => nix.push(other),
      }
   }

   nix.push('"');
   nix
}
